package com.healthcare.kallo.service.nutri;

import com.healthcare.kallo.dto.request.nutri.CopyMealRequest;
import com.healthcare.kallo.dto.request.nutri.CreateFoodLogRequest;
import com.healthcare.kallo.dto.request.nutri.FoodFeedbackRequest;
import com.healthcare.kallo.dto.request.nutri.UpdateFoodLogRequest;
import com.healthcare.kallo.dto.response.food.FoodSearchItemResponse;
import com.healthcare.kallo.dto.response.nutri.CopyMealResponse;
import com.healthcare.kallo.dto.response.nutri.DailyFoodLogsResponse;
import com.healthcare.kallo.dto.response.nutri.FoodLogResponse;
import com.healthcare.kallo.model.food.enums.MealType;
import com.healthcare.kallo.service.sys.sync.SyncApplyResult;
import java.math.BigDecimal;
import java.time.Instant;
import java.time.LocalDate;
import java.util.List;
import java.util.Map;
import java.util.UUID;

/** Service managing user food logs, meal copy, recent foods, and offline sync mutations. */
public interface FoodLogService {

  record CreateResult(FoodLogResponse response, boolean created) {}

  record MealPlanApplyItem(
      UUID foodId,
      MealType mealType,
      BigDecimal servingGrams,
      BigDecimal servingQuantity,
      LocalDate loggedDate,
      Instant loggedAt,
      UUID clientUuid) {}

  CreateResult logFood(UUID userId, CreateFoodLogRequest request);

  DailyFoodLogsResponse getByDate(UUID userId, LocalDate date);

  FoodLogResponse getById(UUID userId, UUID id);

  FoodLogResponse update(UUID userId, UUID id, UpdateFoodLogRequest request);

  void delete(UUID userId, UUID id);

  CopyMealResponse copyMeals(UUID userId, CopyMealRequest request);

  List<FoodSearchItemResponse> getRecentFoods(UUID userId, int limit);

  FoodLogResponse submitFeedback(UUID userId, UUID id, FoodFeedbackRequest request);

  /**
   * Batch-inserts food logs generated by MEAL_PLAN with source MEAL_PLAN and recalculates each
   * affected daily summary once.
   */
  List<FoodLogResponse> applyMealPlanItems(UUID userId, List<MealPlanApplyItem> items);

  SyncApplyResult upsertFromSync(
      UUID userId, UUID clientUuid, Instant opUpdatedAt, Map<String, Object> data);

  SyncApplyResult softDeleteFromSync(UUID userId, UUID clientUuid, Instant opUpdatedAt);
}
